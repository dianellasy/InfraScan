def _add_job(session: Session) -> InferenceJob:
    media = InputMedia(data=b"\xff\xd8jpeg\xff\xd9", content_type="image/jpeg")
    job = InferenceJob(
        input_media=media,
        captured_at=CAPTURED_AT,
        latitude=Decimal("33.8823"),
        longitude=Decimal("-117.8851"),
    )
    session.add(job)
    session.flush()
    return job


def _detection(**overrides: object) -> DetectionRecord:
    values: dict[str, object] = {
        "issue_type": 3,
        "confidence": 0.6575583815574646,
        "severity": "minor",
        "bounding_box": [388.6720886230469, 186.5894012451172, 444.8454895019531, 212.15809631347656],
        "detected_at": DETECTED_AT,
    }
    values.update(overrides)
    return DetectionRecord(**values)


def test_job_has_many_detections_sharing_one_evidence_row(
    session_factory: sessionmaker[Session],
) -> None:
    with session_factory() as session, session.begin():
        job = _add_job(session)
        evidence = EvidenceMedia(job=job, data=b"\xff\xd8annotated", content_type="image/jpeg")
        session.add(evidence)
        job.detection_records.extend(
            [_detection(evidence=evidence), _detection(evidence=evidence, issue_type=2)]
        )
        job_id = job.job_id

    with session_factory() as session:
        job = session.get(InferenceJob, job_id)
        assert job is not None
        assert len(job.detection_records) == 2
        assert len(job.evidence_media) == 1
        evidence = job.evidence_media[0]
        assert {d.evidence_media for d in job.detection_records} == {evidence.media_id}
        assert {d.job.job_id for d in evidence.detection_records} == {job_id}
        record = job.detection_records[0]
        assert record.issue_id is None
        assert record.location is None
        assert record.frame_timestamp is None
        assert record.detected_at == DETECTED_AT


