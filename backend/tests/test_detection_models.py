def _fk_targets(column: sa.Column) -> set[str]:
    return {fk.target_fullname for fk in column.foreign_keys}


def test_detection_record_columns_and_nullability() -> None:
    table = DetectionRecord.__table__
    assert set(table.columns.keys()) == {
        "detection_id",
        "job_id",
        "issue_id",
        "issue_type",
        "evidence_media",
        "location",
        "location_status",
        "location_details",
        "confidence",
        "severity",
        "bounding_box",
        "frame_timestamp",
        "detected_at",
    }
    assert table.c.detection_id.primary_key is True

    required = {"job_id", "issue_type", "confidence", "severity", "bounding_box", "detected_at"}
    nullable = {
        "issue_id",
        "evidence_media",
        "location",
        "location_status",
        "location_details",
        "frame_timestamp",
    }
    for name in required:
        assert table.c[name].nullable is False, name
    for name in nullable:
        assert table.c[name].nullable is True, name

    pg = postgresql.dialect()
    assert isinstance(table.c.issue_type.type, sa.Integer)
    assert isinstance(table.c.confidence.type, sa.Double)
    assert isinstance(table.c.frame_timestamp.type, sa.Double)
    for name in ("bounding_box", "location", "location_details"):
        assert isinstance(table.c[name].type.dialect_impl(pg), postgresql.JSONB)
        assert table.c[name].type.none_as_null is True
    assert table.c.detected_at.type.timezone is True
    # Generated by the worker when inference finishes, not by the database.
    assert table.c.detected_at.server_default is None


def test_detection_record_foreign_keys_and_deferred_issue_references() -> None:
    table = DetectionRecord.__table__

    assert _fk_targets(table.c.job_id) == {"inference_jobs.job_id"}
    assert not table.c.job_id.unique
    job_indexes = [i for i in table.indexes if [c.name for c in i.columns] == ["job_id"]]
    assert len(job_indexes) == 1 and job_indexes[0].unique is False

    assert _fk_targets(table.c.evidence_media) == {"evidence_media.media_id"}

    # Intended FKs to issues / issue_types are deferred until those tables exist.
    assert table.c.issue_id.foreign_keys == set()
    assert table.c.issue_type.foreign_keys == set()

    check_names = {
        c.name for c in table.constraints if isinstance(c, sa.CheckConstraint)
    }
    assert check_names == {
        "ck_detection_records_confidence_range",
        "ck_detection_records_severity_allowed",
        "ck_detection_records_frame_timestamp_nonnegative",
        "ck_detection_records_bounding_box_xyxy",
        "ck_detection_records_location_lat_lon",
        "ck_detection_records_location_status_allowed",
    }
    assert DETECTION_SEVERITIES == ("minor", "moderate", "critical")


