"""Build a single-file Kaggle script from a run body plus our helper modules.

Kaggle script kernels upload one code file. This embeds the helper modules as
text, writes them to disk at start-up, and then runs the body.

Usage:
  # a training run listed in ml/kaggle/runs.json -> ml/kaggle/_build/<name>/{run.py, kernel-metadata.json}
  python ml/kaggle/build_kernel.py --run e1_imgsz736
  kaggle kernels push -p ml/kaggle/_build/e1_imgsz736

  # any other body directly (the data_v1 and dup_analysis CPU jobs); optional KEY=VALUE become default env variables
  python ml/kaggle/build_kernel.py ml/kaggle/<job>/body.py ml/kaggle/<job>/run.py [KEY=VALUE ...]
"""

import base64
import json
import re
import sys
from pathlib import Path

KAGGLE = Path(__file__).resolve().parent
ML = KAGGLE.parent
MODULES = {
    "prepare_rdd2022.py": ML / "data" / "prepare_rdd2022.py",
    "evaluate.py": ML / "eval" / "evaluate.py",
    "boxes.py": ML / "eval" / "boxes.py",
}


def needed_modules(body_text):
    """Helper modules the body imports or runs by file name ("prepare_rdd2022.py"), directly or through another
    helper (only those get embedded)."""
    def imports(text):
        return {name for name in MODULES
                if re.search(rf"^\s*(import|from)\s+{re.escape(name[:-3])}\b", text, re.MULTILINE)
                or re.search(rf"[\"']{re.escape(name)}[\"']", text)}

    need, todo = set(), imports(body_text)
    while todo:
        name = todo.pop()
        need.add(name)
        todo |= imports(MODULES[name].read_text(encoding="utf-8")) - need
    return [n for n in MODULES if n in need]
TRAIN_BODY = KAGGLE / "train" / "body.py"
RUNS = KAGGLE / "runs.json"
SOURCES = {  # short source name in runs.json -> (kernel-metadata field, Kaggle id)
    "data_v1": ("kernel_sources", "adarshjaiswal2234/infrascan-data-v1"),
    "cmird": ("dataset_sources", "adarshjaiswal2234/infrascan-cmird-pothole"),
}


def build(body, out, env):
    head = ["# AUTO-GENERATED by ml/kaggle/build_kernel.py. Edit body.py and the helper modules instead.",
            "import base64, os, sys",
            "SRC = os.path.join(os.environ.get('WORK_DIR', '/kaggle/working'), 'src')",
            "os.makedirs(SRC, exist_ok=True)"]
    body_text = Path(body).read_text(encoding="utf-8")
    for name in needed_modules(body_text):
        b64 = base64.b64encode(MODULES[name].read_bytes()).decode()
        head.append(f"open(os.path.join(SRC, {name!r}), 'wb').write(base64.b64decode({b64!r}))")
    # Settings become default environment variables of the built kernel, so one body serves many runs.
    for key, value in env.items():
        head.append(f"os.environ.setdefault({key!r}, {str(value)!r})")
    head.append("sys.path.insert(0, SRC)")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(head) + "\n\n" + body_text, encoding="utf-8")
    print(f"wrote {out}")


def build_run(name):
    runs = json.loads(RUNS.read_text(encoding="utf-8"))["runs"]
    if name not in runs:
        raise SystemExit(f"unknown run {name!r}; known: {', '.join(runs)}")
    r = runs[name]
    out_dir = KAGGLE / "_build" / name
    build(TRAIN_BODY, out_dir / "run.py", {"RUN": name, **r.get("env", {})})
    meta = {"id": r["kernel"], "title": f"InfraScan {name}", "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
            "enable_internet": "true", "machine_shape": "", "dataset_sources": [], "competition_sources": [],
            "kernel_sources": [], "model_sources": []}
    for s in r.get("sources", []):
        field, kid = SOURCES[s]
        meta[field].append(kid)
    (out_dir / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out_dir / 'kernel-metadata.json'}")
    return out_dir


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--run":
        build_run(sys.argv[2])
    elif len(sys.argv) >= 3:
        build(sys.argv[1], Path(sys.argv[2]), dict(a.partition("=")[::2] for a in sys.argv[3:]))
    else:
        raise SystemExit(__doc__)
