"""Build a single-file Kaggle script from a run body plus our helper modules.

Kaggle script kernels upload one code file. This embeds the helper modules as
text, writes them to disk at start-up, and then runs the body.

Usage: python ml/kaggle/build_kernel.py ml/kaggle/<run>/body.py ml/kaggle/<run>/run.py
"""

import base64
import sys
from pathlib import Path

ML = Path(__file__).resolve().parents[1]
MODULES = {
    "prepare_rdd2022.py": ML / "data" / "prepare_rdd2022.py",
    "evaluate.py": ML / "eval" / "evaluate.py",
}

body, out = Path(sys.argv[1]), Path(sys.argv[2])
head = ["# AUTO-GENERATED by ml/kaggle/build_kernel.py. Edit body.py and the helper modules instead.",
        "import base64, os, sys", "SRC = os.path.join(os.environ.get('WORK_DIR', '/kaggle/working'), 'src')", "os.makedirs(SRC, exist_ok=True)"]
for name, path in MODULES.items():
    b64 = base64.b64encode(path.read_bytes()).decode()
    head.append(f"open(os.path.join(SRC, {name!r}), 'wb').write(base64.b64decode({b64!r}))")
head.append("sys.path.insert(0, SRC)")
out.write_text("\n".join(head) + "\n\n" + body.read_text(), encoding="utf-8")
print(f"wrote {out}")
